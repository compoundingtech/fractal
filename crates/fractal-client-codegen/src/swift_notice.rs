use anyhow::Result;
use serde_json::Value;
use std::fmt::Write as _;

pub fn models(schema: &Value) -> Result<String> {
    let mut out =
        String::from("// Generated by fractal-client-codegen; do not edit.\nimport Foundation\n\n");
    out.push_str(include_str!("../templates/WireValidation.swift.in"));
    for (name, node) in crate::notice_schema::closure(schema)? {
        emit(&name, &node, &mut out)?;
    }
    Ok(out)
}

fn emit(name: &str, node: &Value, out: &mut String) -> Result<()> {
    if let Some(reference) = node["$ref"].as_str() {
        writeln!(
            out,
            "public typealias {name} = {}\n",
            reference.trim_start_matches("#/$defs/")
        )?;
        return Ok(());
    }
    if let Some(branches) = node["oneOf"].as_array() {
        for (i, branch) in branches.iter().enumerate() {
            emit(&format!("{name}Variant{i}"), branch, out)?;
        }
        writeln!(out, "public enum {name}: Codable, Sendable, Hashable {{")?;
        for i in 0..branches.len() {
            writeln!(out, "    case variant{i}({name}Variant{i})")?;
        }
        for i in 0..branches.len() {
            writeln!(
                out,
                "    public init(_ value: {name}Variant{i}) throws {{ self = .variant{i}(value) }}"
            )?;
        }
        writeln!(
            out,
            "    public init(from decoder: Decoder) throws {{\n        var result: Self?\n        var matches = 0"
        )?;
        for i in 0..branches.len() {
            writeln!(
                out,
                "        if let value = try? {name}Variant{i}(from: decoder) {{ result = .variant{i}(value); matches += 1 }}"
            )?;
        }
        writeln!(
            out,
            "        guard matches == 1, let result else {{ throw WireValidation.error(\"{name}: expected exactly one variant\") }}\n        self = result\n    }}\n    public func encode(to encoder: Encoder) throws {{\n        switch self {{"
        )?;
        for i in 0..branches.len() {
            writeln!(
                out,
                "        case .variant{i}(let value): try value.encode(to: encoder)"
            )?;
        }
        writeln!(out, "        }}\n    }}\n}}\n")?;
        return Ok(());
    }
    if node["type"] == "object" {
        let fields = node["properties"].as_object().expect("validated object");
        let required = node["required"].as_array().expect("validated required");
        let is_required = |key: &str| required.iter().any(|v| v == key);
        for (key, field) in fields {
            emit(&format!("{name}{}", crate::pascal(key)), field, out)?;
        }
        writeln!(out, "public struct {name}: Codable, Sendable, Hashable {{")?;
        for key in fields.keys() {
            writeln!(
                out,
                "    public let `{}`: {name}{}{}",
                crate::lower_camel_snake(key),
                crate::pascal(key),
                if is_required(key) { "" } else { "?" }
            )?;
        }
        let args = fields
            .keys()
            .map(|key| {
                format!(
                    "`{}`: {name}{}{}",
                    crate::lower_camel_snake(key),
                    crate::pascal(key),
                    if is_required(key) { "" } else { "? = nil" }
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(out, "    public init({args}) throws {{")?;
        for key in fields.keys() {
            let prop = crate::lower_camel_snake(key);
            writeln!(out, "        self.`{prop}` = `{prop}`")?;
        }
        writeln!(out, "    }}\n    enum CodingKeys: String, CodingKey {{")?;
        for key in fields.keys() {
            writeln!(
                out,
                "        case `{}` = {key:?}",
                crate::lower_camel_snake(key)
            )?;
        }
        writeln!(
            out,
            "    }}\n    public init(from decoder: Decoder) throws {{\n        let keys = try decoder.container(keyedBy: WireValidation.Key.self)\n        guard keys.allKeys.allSatisfy({{ CodingKeys(rawValue: $0.stringValue) != nil }}) else {{ throw WireValidation.error(\"{name}: unknown property\") }}\n        let container = try decoder.container(keyedBy: CodingKeys.self)"
        )?;
        for key in fields.keys() {
            let prop = crate::lower_camel_snake(key);
            let ty = format!("{name}{}", crate::pascal(key));
            let decode = format!("try container.decode({ty}.self, forKey: .`{prop}`)");
            writeln!(
                out,
                "        self.`{prop}` = {}",
                if is_required(key) {
                    decode
                } else {
                    format!("container.contains(.`{prop}`) ? {decode} : nil")
                }
            )?;
        }
        writeln!(out, "    }}\n}}\n")?;
        return Ok(());
    }
    let choices = node["enum"].as_array().cloned().or_else(|| {
        node.get("const")
            .and_then(Value::as_str)
            .map(|s| vec![Value::String(s.into())])
    });
    if let Some(choices) = choices {
        writeln!(
            out,
            "public enum {name}: String, Codable, Sendable, Hashable {{"
        )?;
        for value in choices {
            let value = value.as_str().expect("string enum");
            writeln!(
                out,
                "    case `{}` = {value:?}",
                crate::lower_camel(&crate::pascal(value))
            )?;
        }
        writeln!(
            out,
            "    public init(_ value: String) throws {{\n        guard let result = Self(rawValue: value) else {{ throw WireValidation.error(\"{name}: invalid value\") }}\n        self = result\n    }}\n}}\n"
        )?;
        return Ok(());
    }
    if node["type"] == "null" {
        writeln!(
            out,
            "public struct {name}: Codable, Sendable, Hashable {{\n    public init() throws {{}}\n    public init(from decoder: Decoder) throws {{\n        guard try decoder.singleValueContainer().decodeNil() else {{ throw WireValidation.error(\"{name}: expected null\") }}\n    }}\n    public func encode(to encoder: Encoder) throws {{ var container = encoder.singleValueContainer(); try container.encodeNil() }}\n}}\n"
        )?;
        return Ok(());
    }
    let ty = match node["type"].as_str() {
        Some("array") => {
            emit(&format!("{name}Item"), &node["items"], out)?;
            format!("[{name}Item]")
        }
        Some("string") => "String".into(),
        Some("boolean") => "Bool".into(),
        _ => "UInt64".into(),
    };
    writeln!(
        out,
        "public struct {name}: Codable, Sendable, Hashable {{\n    public let value: {ty}"
    )?;
    let mut guards = Vec::new();
    for (key, comparison, count) in [
        ("minLength", ">=", "unicodeScalars.count"),
        ("maxLength", "<=", "unicodeScalars.count"),
        ("minItems", ">=", "count"),
        ("maxItems", "<=", "count"),
    ] {
        if let Some(bound) = node[key].as_u64() {
            guards.push(format!("value.{count} {comparison} {bound}"));
        }
    }
    if node["uniqueItems"] == true {
        guards.push("Set(value).count == value.count".into());
    }
    if let Some(value) = node["const"].as_u64() {
        guards.push(format!("value == {value}"));
    }
    for (key, pattern) in [
        ("pattern", node["pattern"].as_str().map(str::to_owned)),
        (
            "uri",
            (node["format"] == "uri-reference").then(crate::rich::uri_reference_pattern),
        ),
    ] {
        if let Some(pattern) = pattern {
            let pattern = pattern.replace("$(?![\\s\\S])", "\\z");
            let pattern = pattern
                .strip_suffix('$')
                .map_or_else(|| pattern.clone(), |prefix| format!("{prefix}\\z"));
            writeln!(
                out,
                "    private static let {key} = try! NSRegularExpression(pattern: {pattern:?})"
            )?;
            guards.push(format!("Self.{key}.firstMatch(in: value, range: NSRange(value.startIndex..., in: value)) != nil"));
        }
    }
    if node["format"] == "date-time" {
        guards.push("WireValidation.utc(value)".into());
    }
    writeln!(out, "    public init(_ value: {ty}) throws {{")?;
    if !guards.is_empty() {
        writeln!(
            out,
            "        guard {} else {{ throw WireValidation.error(\"{name}: constraint violation\") }}",
            guards.join(", ")
        )?;
    }
    writeln!(
        out,
        "        self.value = value\n    }}\n    public init(from decoder: Decoder) throws {{ try self.init(decoder.singleValueContainer().decode({ty}.self)) }}\n    public func encode(to encoder: Encoder) throws {{ var container = encoder.singleValueContainer(); try container.encode(value) }}\n}}\n"
    )?;
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn rejects_unsupported_constraints_and_emits_native_checks() {
        let schema: serde_json::Value = serde_json::from_str(include_str!(
            "../../../docs/st3/client-v0/schemas/client-v0.schema.json"
        ))
        .unwrap();
        let generated = super::models(&schema).unwrap();
        for check in [
            "unicodeScalars.count",
            "Set(value).count",
            "WireValidation.utc(value)",
            "NSRegularExpression",
            "container.contains",
        ] {
            assert!(generated.contains(check), "missing {check}");
        }
        let mut unsupported = schema;
        unsupported["$defs"]["NoticeTimestamp"]["minProperties"] = 1.into();
        assert!(super::models(&unsupported).is_err());
    }
}
