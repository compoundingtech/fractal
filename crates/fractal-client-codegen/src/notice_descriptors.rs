use anyhow::{Context as _, Result, ensure};
use serde_json::{Value, json};
use std::fmt::Write as _;

/// Internal insertion content only: neither Resource nor the operation manifest is extended.
pub fn models(schema: &Value) -> Result<String> {
    let closed = crate::notice_schema::closure(schema)?;
    let entries = schema["x-st-internal-resources"]
        .as_object()
        .context("internal resource metadata")?;
    let mut descriptors = Vec::new();
    let mut decoders = String::new();
    for (model, metadata) in entries {
        ensure!(
            metadata.as_object().is_some_and(|o| o.len() == 1),
            "internal metadata contains only collection"
        );
        let collection = metadata["collection"]
            .as_str()
            .context("internal collection")?;
        let definition = closed
            .get(model)
            .context("internal resource belongs to notice closure")?;
        let kind = definition["properties"]["kind"]["const"]
            .as_str()
            .context("resource kind constant")?;
        ensure!(
            !kind.is_empty() && kind.bytes().all(|c| c.is_ascii_lowercase() || c == b'-'),
            "resource kind naming"
        );
        let id = definition["properties"]["id"]["$ref"]
            .as_str()
            .context("resource identifier reference")?;
        let id = id
            .strip_prefix("#/$defs/")
            .context("local identifier reference")?;
        ensure!(closed.contains_key(id), "identifier belongs to closure");
        descriptors.push(json!({"model": model, "kind": kind, "collection": collection, "id_schema": id, "internal": true}));
        writeln!(
            decoders,
            "pub(crate) fn decode_{}(wire: &[u8]) -> serde_json::Result<super::notice_models::{model}> {{ serde_json::from_slice(wire) }}",
            kind.replace('-', "_")
        )?;
    }
    let json = serde_json::to_string(&descriptors)?;
    Ok(format!(
        "// Generated by fractal-client-codegen; internal insertion content, not server support.\npub(crate) const DESCRIPTORS_JSON: &str = {json:?};\n{decoders}"
    ))
}

#[cfg(test)]
mod tests {
    #[test]
    fn descriptors_stay_internal_and_decode_directly() {
        let mut schema: serde_json::Value = serde_json::from_str(include_str!(
            "../../../docs/st3/client-v0/schemas/client-v0.schema.json"
        ))
        .unwrap();
        let source = super::models(&schema).unwrap();
        assert!(source.contains("pub(crate) fn decode_attention_notice"));
        assert!(source.contains("serde_json::from_slice(wire)"));
        for forbidden in ["Unknown", "to_value", "from_value", "pub fn"] {
            assert!(!source.contains(forbidden), "{forbidden}");
        }
        schema["x-st-internal-resources"]["Resource"] =
            serde_json::json!({"collection": "notices"});
        assert!(super::models(&schema).is_err());
    }
}
