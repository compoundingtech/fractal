//! Internal notice models: closed schema traversal, with no transport registration.
use anyhow::{Context as _, Result, bail};
use serde_json::{Value, json};
use std::fmt::Write as _;

pub fn models(schema: &Value) -> Result<(String, String)> {
    let closed = crate::notice_schema::closure(schema)?;
    let mut out = String::from("// Generated by fractal-client-codegen; do not edit.\n");
    out.push_str("use serde::{Deserialize, Serialize};\nuse serde_json::Value;\n");
    // Each named model is independently decodable. Validators are compiled once.
    for (name, node) in &closed {
        emit(name, node, &mut out)?;
    }
    Ok((
        out,
        serde_json::to_string_pretty(&json!({"$defs": closed}))? + "\n",
    ))
}

fn pascal(name: &str) -> String {
    name.split(['_', '-'])
        .map(|part| {
            let mut c = part.chars();
            c.next()
                .map(|first| first.to_uppercase().collect::<String>() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn emit(name: &str, node: &Value, out: &mut String) -> Result<()> {
    if let Some(reference) = node["$ref"].as_str() {
        writeln!(
            out,
            "pub type {name} = {};",
            reference.strip_prefix("#/$defs/").context("local ref")?
        )?;
        return Ok(());
    }
    let mut nested = String::new();
    let declaration = if let Some(branches) = node["oneOf"].as_array() {
        let mut variants = String::new();
        for (index, branch) in branches.iter().enumerate() {
            let child = format!("{name}Variant{index}");
            emit(&child, branch, &mut nested)?;
            writeln!(variants, "Variant{index}({child}),")?;
        }
        format!("#[serde(untagged)]\npub enum {name} {{ {variants} }}")
    } else if let Some(values) = node["enum"].as_array().map(Vec::as_slice).or_else(|| {
        node.get("const")
            .filter(|v| v.is_string())
            .map(std::slice::from_ref)
    }) {
        let mut variants = String::new();
        for value in values {
            let text = value.as_str().context("only string enums supported")?;
            writeln!(variants, "#[serde(rename = {text:?})] {},", pascal(text))?;
        }
        format!("pub enum {name} {{ {variants} }}")
    } else if node["type"] == "object" {
        let mut fields = String::new();
        for (field, child) in node["properties"].as_object().context("properties")? {
            let child_name = format!("{name}{}", pascal(field));
            emit(&child_name, child, &mut nested)?;
            let required = node["required"]
                .as_array()
                .context("required")?
                .contains(&json!(field));
            let ty = if required {
                child_name
            } else {
                format!("Option<{child_name}>")
            };
            if !required {
                fields.push_str("#[serde(default, skip_serializing_if = \"Option::is_none\")]\n");
            }
            writeln!(fields, "pub {field}: {ty},")?;
        }
        format!("#[serde(deny_unknown_fields)]\npub struct {name} {{ {fields} }}")
    } else {
        let ty = match node["type"].as_str() {
            Some("string") => "String".to_owned(),
            Some("boolean") => "bool".to_owned(),
            Some("null") => "()".to_owned(),
            Some("array") => {
                let child = format!("{name}Item");
                emit(&child, &node["items"], &mut nested)?;
                format!("Vec<{child}>")
            }
            None if node["const"].is_u64() => "u64".to_owned(),
            _ => bail!("unsupported Rust notice type: {node}"),
        };
        format!("pub struct {name}(pub {ty});")
    };
    // Remote derive decodes the typed shape without re-entering this type's validator.
    let raw = declaration
        .replace(&format!("pub struct {name}"), &format!("struct {name}Raw"))
        .replace(&format!("pub enum {name}"), &format!("enum {name}Raw"));
    // Child models enforce their own constraints; do not revalidate whole subtrees.
    // Optional fields retain validation because serde Option also accepts null.
    let mut local = node.clone();
    if let Some(properties) = local.get_mut("properties").and_then(Value::as_object_mut) {
        for (field, child) in properties {
            if node["required"]
                .as_array()
                .is_some_and(|r| r.contains(&json!(field)))
            {
                *child = json!({});
            }
        }
    }
    if node["type"] == "array" {
        local["items"] = json!({});
    }
    writeln!(
        out,
        "#[derive(Debug, Clone, PartialEq, Serialize)]\n{declaration}"
    )?;
    writeln!(
        out,
        "impl<'de> Deserialize<'de> for {name} {{ fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {{\nlet value = Value::deserialize(d)?;\nstatic VALIDATOR: std::sync::LazyLock<jsonschema::Validator> = std::sync::LazyLock::new(|| {{ let mut schema: Value = serde_json::from_str(include_str!(\"notice_schema.generated.json\")).expect(\"generated schema\"); schema[\"allOf\"] = serde_json::json!([{}]); jsonschema::options().should_validate_formats(true).build(&schema).expect(\"supported notice schema\") }});\nVALIDATOR.validate(&value).map_err(serde::de::Error::custom)?;\n#[derive(Deserialize)]\n#[serde(remote = \"{name}\")]\n{raw}\n{name}Raw::deserialize(value).map_err(serde::de::Error::custom)\n}} }}",
        serde_json::to_string(&local)?
    )?;
    out.push_str(&nested);
    Ok(())
}
