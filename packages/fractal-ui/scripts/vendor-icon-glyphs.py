#!/usr/bin/env python3
"""Vendor the Lucide glyph data the kit icon registry uses, as TypeScript data.

The archive is the pinned lucide-static tarball, verified against its npm SHA-512 integrity.
Only the listed glyphs are emitted, with the package's LICENSE verbatim. No runtime dependency.
`--check` regenerates in memory and fails when the committed file differs.
"""

import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import sys
import tarfile
from urllib.request import urlopen

PACKAGE = "lucide-static"
VERSION = "1.55.0"
LICENSE = "ISC"
# The package is ISC, and its LICENSE also carries the Feather MIT notice for the Feather-derived glyphs.
# Both apply to the vendored file, so its header (and the license inventory) records both.
NOTICE_LICENSES = "ISC AND MIT"
REGISTRY = "https://registry.npmjs.org"
INTEGRITY = "sha512-h18lunTFsIJWnY0FMRPjXeO9KcAtNi7fDqtqgWHOFbssfgUWsctn/pA7bpiyrd4g1DuBOJ24CsRnPfkYblwm/A=="
OUTPUT = Path(__file__).resolve().parent.parent / "src/assistant-ui/composition/icon-glyphs.generated.ts"
# Canonical Lucide names. The registry (icon-registry.ts) maps every meaning to one of these;
# its unit test fails when a vendored glyph has no meaning.
GLYPHS = sorted([
    "activity", "anchor", "app-window", "arrow-down", "arrow-down-wide-narrow", "arrow-left", "arrow-up",
    "arrow-up-right", "at-sign", "bell", "book-open", "bot", "brain", "calendar-clock", "check",
    "chevron-down", "chevron-left", "chevron-right", "chevron-up", "chevrons-up-down", "circle",
    "circle-alert", "circle-check", "circle-dashed", "circle-minus", "circle-question-mark", "circle-slash",
    "circle-stop", "circle-x", "clock", "code", "coins", "columns-2", "copy", "cpu", "ellipsis", "eye",
    "eye-off", "file", "file-diff", "file-pen", "file-text", "flag", "fold-vertical", "folder", "folder-open",
    "folder-plus", "gauge", "git-branch", "git-pull-request", "globe", "grip-vertical", "hourglass", "image",
    "image-plus", "inbox", "info", "layers", "link", "list", "list-checks", "list-filter", "message-square",
    "message-square-plus", "message-square-text", "moon", "network", "panel-bottom", "panel-left",
    "panel-left-close", "panel-left-open", "panel-right", "paperclip", "pencil", "pilcrow", "plus",
    "presentation", "rotate-ccw", "rotate-ccw-clock", "rows-2", "search", "send", "server", "server-cog", "settings",
    "signal-medium", "sliders-horizontal", "square", "square-pen", "square-terminal", "sun", "text-wrap",
    "timer", "triangle-alert", "x", "zap",
])
TAGS = {"path", "circle", "rect", "line", "polyline"}


def archive():
    with urlopen(f"{REGISTRY}/{PACKAGE}/-/{PACKAGE}-{VERSION}.tgz", timeout=60) as response:
        data = response.read()
    if hashlib.sha512(data).digest() != base64.b64decode(INTEGRITY.removeprefix("sha512-"), validate=True):
        raise ValueError(f"{PACKAGE}@{VERSION} archive integrity mismatch")
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        def member(name):
            return tar.extractfile(tar.getmember(f"package/{name}")).read().decode()
        manifest = json.loads(member("package.json"))
        if (manifest.get("name"), manifest.get("version"), manifest.get("license")) != (PACKAGE, VERSION, LICENSE):
            raise ValueError("archive manifest does not match the pinned package, version and license")
        return json.loads(member("icon-nodes.json")), member("LICENSE")


def literal(value):
    return json.dumps(value, ensure_ascii=False).replace("'", "\\'").replace('"', "'")


def render(nodes, license_text):
    if len(GLYPHS) != len(set(GLYPHS)):
        raise ValueError("duplicate glyph names")
    if "*/" in license_text:
        raise ValueError("license text cannot be embedded in a block comment")
    if "ISC License" not in license_text or "The MIT License" not in license_text:
        raise ValueError("expected both the ISC and the Feather MIT notices in the package LICENSE")
    fingerprint = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    lines = [
        "// GENERATED by packages/fractal-ui/scripts/vendor-icon-glyphs.py; do not edit by hand.",
        "// Regenerate: python3 packages/fractal-ui/scripts/vendor-icon-glyphs.py (verify: --check)",
        f"// Source: {PACKAGE}@{VERSION} ({NOTICE_LICENSES}), the npm registry archive with the integrity below",
        f"// Integrity: {INTEGRITY}",
        f"// Input fingerprint: sha256:{fingerprint}",
        "/*",
        license_text.rstrip("\n"),
        "*/",
        "",
        "export type GlyphNode = readonly [tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline', attributes: Readonly<Record<string, string>>]",
        "",
        "/** Lucide glyph geometry on its 24-unit grid: element tag plus SVG attributes. */",
        "export const lucideGlyphs = {",
    ]
    for name in GLYPHS:
        if name not in nodes:
            raise ValueError(f"{PACKAGE}@{VERSION} has no glyph {name}")
        parts = []
        for tag, attributes in nodes[name]:
            if tag not in TAGS or not all(key.isalnum() for key in attributes):
                raise ValueError(f"unsupported element in {name}: {tag} {attributes}")
            parts.append(f"[{literal(tag)}, {{ {', '.join(f'{key}: {literal(value)}' for key, value in attributes.items())} }}]")
        lines.append(f"  {literal(name)}: [{', '.join(parts)}],")
    lines += ["} as const satisfies Record<string, readonly GlyphNode[]>", "", "export type LucideGlyphName = keyof typeof lucideGlyphs", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the committed file differs from the pinned archive")
    args = parser.parse_args()
    expected = render(*archive())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise ValueError(f"{OUTPUT.name} is stale; run python3 packages/fractal-ui/scripts/vendor-icon-glyphs.py")
        print(f"Icon glyphs match {PACKAGE}@{VERSION}: {len(GLYPHS)} glyphs")
    elif not OUTPUT.exists() or OUTPUT.read_text() != expected:
        if OUTPUT.exists():
            OUTPUT.chmod(0o644)
        OUTPUT.write_text(expected)
        print(f"Vendored {len(GLYPHS)} glyphs from {PACKAGE}@{VERSION}")
    # Git does not retain read-only permissions; generation and checks restore them.
    OUTPUT.chmod(0o444)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, OSError, KeyError, tarfile.TarError) as error:
        print(f"Icon glyph vendoring failed: {error}", file=sys.stderr)
        raise SystemExit(1)
