import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { isSupportedLanguage } from '@pierre/highlights'

export const output = new URL('../src/assistant-ui/composition/pierre-languages.generated.ts', import.meta.url)

// Pierre has no lightweight language-list export. Its published declaration
// contains every ID and alias; verify each entry against the runtime API.
export async function generatedLanguages() {
  const declaration = await readFile(new URL('./dist/languages.d.ts', import.meta.resolve('@pierre/highlights/package.json')), 'utf8')
  const languages = [...declaration.matchAll(/^  readonly (?:'([^']+)'|([\w-]+)): \d+;$/gm)]
    .map(match => match[1] ?? match[2]).sort()
  if (languages.length === 0 || languages.some(language => !isSupportedLanguage(language))) {
    throw new Error('Pierre language declaration no longer matches its runtime API')
  }
  return `// Generated by scripts/pierre-languages.mjs; DO NOT EDIT.\nconst languages = new Set(${JSON.stringify(languages)})\n\nexport const isSupportedFenceLanguage = (language: string): boolean => languages.has(language)\n`
}

export async function checkGeneratedLanguages(committed) {
  if (committed !== await generatedLanguages()) {
    throw new Error('Pierre language list drift: run pnpm --dir packages/fractal-ui run generate:pierre-languages')
  }
}

export function pierreLanguagesPlugin() {
  return {
    name: 'fractal:pierre-languages',
    async buildStart() {
      await checkGeneratedLanguages(await readFile(output, 'utf8'))
    },
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    await checkGeneratedLanguages(await readFile(output, 'utf8'))
  } else {
    await writeFile(output, await generatedLanguages())
  }
}
