// Prints the host mission for a program: one agentless step whose exec is the driver.
// Usage: node host.ts PROGRAM_FILE [--lab] [--name MISSION] [--ref doc/NAME@SHA] [--extra "DRIVER FLAGS"]
// With --ref, the driver loads that stored version instead of a file path.
import { resolve } from "node:path"
import { pathToFileURL } from "node:url"

const file = resolve(process.argv[2]!)
const lab = process.argv.includes("--lab")
const mod = await import(pathToFileURL(file).href)
const program = mod.program ?? mod.default // a version bundle or a development .ts
const opt = (flag: string) => {
  const i = process.argv.indexOf(flag)
  return i >= 0 ? process.argv[i + 1] : undefined
}
const name = opt("--name") ?? program.name
const extra = opt("--extra") ? ` ${opt("--extra")}` : ""
const driver = resolve(import.meta.dirname, "driver.ts")
const flags = (lab ? ` --lab-worker ${resolve(import.meta.dirname, "lab/worker.sh")} --time-scale 600 --poll-ms 500` : "") + extra

console.log(`version 2

// Generated by exp2-driver/host.ts. The program's ops appear as child runs <run>/op/<op>;
// its journal is custom/mac/journal/<run>.
mission "${name}" state="ready" {
  concurrent-runs
  goal "Run the ${program.name} program to completion."
  input "program-input" kind="text"

  step "program" {
    agentless
    title "Program ${program.name}"
    exec "driver" {
      host "local"
      workspace "\${ST_WORKSPACE}"
      command "node ${driver} --program ${opt("--ref") ?? file}${flags}"
      restart "on-failure"
    }
    gate "the program completed" {
      field "exit_code" "exec/\${ST_MISSION_RUN}/driver" "is" 0
    }
  }
}`)
